// Contents tab of the left sidebar: the PDF's own outline when it has one, otherwise a table of
// contents the OpenRouter model builds from the heading-like lines of the document. A generated
// table is saved with the paper's notes, so it is only built once.

import { buildLines } from './citations.js';

const $ = (id) => document.getElementById(id);
const el = (tag, props = {}, ...children) => {
  const node = Object.assign(document.createElement(tag), props);
  node.append(...children.filter((c) => c != null));
  return node;
};

const NUMBERED = /^((\d{1,2}(\.\d{1,2}){0,3}\.?)|([A-Z](\.\d{1,2}){0,3}\.?)|([IVX]{1,5}\.))\s+[A-Z]/;
const KEYWORD =
  /^(abstract|introduction|related work|background|preliminaries|methods?|methodology|approach|experiments?|evaluation|results|discussion|limitations|conclusions?|future work|acknowledge?ments?|references|bibliography|appendix|appendices|supplementary)\b/i;
const MAX_PAGES = 300;
const MAX_LINES = 900;

// Lines that could be section headings, with the body text size they are judged against.
export async function headingCandidates(pdf) {
  const lines = [];
  const pages = Math.min(pdf.numPages, MAX_PAGES);
  for (let p = 1; p <= pages; p++) {
    const page = await pdf.getPage(p);
    const content = await page.getTextContent();
    for (const line of buildLines(content.items)) lines.push({ ...line, page: p, text: line.text.replace(/\s+/g, ' ').trim() });
  }
  // Body text is whatever size and font carry the most characters.
  const tally = (key) => {
    const counts = new Map();
    for (const l of lines) counts.set(key(l), (counts.get(key(l)) || 0) + l.text.length);
    return [...counts].sort((a, b) => b[1] - a[1])[0]?.[0];
  };
  const size = (l) => Math.round(l.h * 2) / 2;
  const bodySize = tally(size) || 10;
  const bodyFont = tally((l) => l.font);

  const short = lines.filter((l) => {
    const words = l.text.split(' ').length;
    return l.text.length >= 3 && l.text.length <= 140 && words <= 16 && /[A-Za-z]{3}/.test(l.text);
  });
  const strong = (l) => size(l) > bodySize + 0.4 || NUMBERED.test(l.text) || KEYWORD.test(l.text);
  // Same-size headings usually differ from the body only by font (bold); keep those too when they fit.
  const styled = (l) => l.font !== bodyFont && size(l) >= bodySize - 0.4 && l.text.split(' ').length <= 10 && /^[A-Z0-9]/.test(l.text);
  let picked = short.filter((l) => strong(l) || styled(l));
  if (picked.length > MAX_LINES) picked = short.filter(strong);
  picked = picked.slice(0, MAX_LINES).map((l, id) => ({ id, page: l.page, size: size(l), text: l.text, top: l.y + l.h }));
  return { bodySize, lines: picked };
}

export function initToc(ctx) {
  const { api, pdfViewer } = ctx;
  const list = $('toc-list');
  let shownFor = null; // document id whose contents are on screen
  let run = 0;

  const hint = (text, ...extra) => list.replaceChildren(el('p', { className: 'hint', textContent: text }), ...extra);

  function row(title, level, onclick, page) {
    const item = el('button', { className: 'toc-item', title, onclick },
      el('span', { className: 'toc-title', textContent: title }),
      page ? el('span', { className: 'toc-page', textContent: String(page) }) : null);
    item.style.paddingLeft = `${8 + (level - 1) * 14}px`;
    return item;
  }

  function outlineRows(items, level = 1) {
    return items.flatMap((item) => {
      const go = () => (item.dest ? ctx.goToDestination(item.dest) : item.url && api.openExternal(item.url));
      return [row((item.title || '').replace(/\s+/g, ' ').trim() || '(untitled)', Math.min(level, 5), go), ...outlineRows(item.items || [], level + 1)];
    });
  }

  function showGenerated(toc, doc) {
    const goTo = (it) => pdfViewer.scrollPageIntoView({ pageNumber: it.page, destArray: [null, { name: 'XYZ' }, null, it.top + 6, null] });
    list.replaceChildren(
      ...toc.items.map((it) => row(it.title, it.level, () => goTo(it), it.page)),
      el('p', { className: 'hint toc-foot' },
        `Generated by ${toc.model || 'AI'}; headings can be missing or misplaced. `,
        el('button', { className: 'tb small', textContent: 'Regenerate', onclick: () => generate(doc) })));
  }

  async function generate(doc) {
    const id = ++run;
    const current = () => id === run && ctx.doc === doc;
    list.replaceChildren(el('p', { className: 'hint loading', textContent: 'This PDF has no table of contents. Building one from its headings…' }));
    let res;
    try {
      const input = await headingCandidates(doc.pdf);
      if (!current()) return;
      if (!input.lines.length) return hint('No headings were found in this PDF’s text. Scanned PDFs without a text layer cannot be outlined.');
      res = await api.generateToc({ bodySize: input.bodySize, lines: input.lines.map(({ id: n, page, size, text }) => ({ id: n, page, size, text })) });
      if (res.items) {
        const byId = new Map(input.lines.map((l) => [l.id, l]));
        res.items = res.items.filter((it) => byId.has(it.id)).map((it) => ({ title: it.title, level: it.level, page: byId.get(it.id).page, top: Math.round(byId.get(it.id).top) }));
      }
    } catch (err) {
      res = { error: err.message };
    }
    if (!current()) return;
    const retry = el('button', { textContent: 'Try again', onclick: () => generate(doc) });
    if (res.error) return hint(`Could not build a table of contents: ${res.error}`, retry);
    if (!res.items.length) return hint('The model found no section headings in this PDF.', retry);
    const toc = { model: res.model, items: res.items };
    ctx.annotations.setMeta(doc.id, 'toc', toc);
    showGenerated(toc, doc);
  }

  // Called when the tab is shown and when a document opens; does nothing while the tab is hidden.
  async function refresh() {
    const doc = ctx.doc;
    if ($('side-toc').hidden || $('sidebar').hidden) return;
    if (!doc) return hint('Open a PDF to see its table of contents.');
    if (shownFor === doc.id) return;
    const id = ++run;
    const outline = await doc.pdf.getOutline().catch(() => null);
    if (id !== run || ctx.doc !== doc) return;
    shownFor = doc.id;
    if (outline?.length) return list.replaceChildren(...outlineRows(outline));
    const saved = ctx.annotations.getMeta('toc');
    if (saved?.items?.length) return showGenerated(saved, doc);
    if ((await api.getSettings()).hasOpenRouterKey) return generate(doc);
    shownFor = null; // look again next time, in case a key has been added
    hint('This PDF has no table of contents. Add an OpenRouter API key in Settings and Paper Pal will build one from the headings.');
  }

  return {
    refresh,
    docChanged: () => {
      shownFor = null;
      run++;
      list.replaceChildren();
      refresh();
    },
  };
}
